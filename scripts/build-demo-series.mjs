// Regenerates lib/demo-series.ts from the recorded REAL YouCam responses in fixtures/series/.
// node scripts/build-demo-series.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
const dir = new URL("../fixtures/series/", import.meta.url);
const files = readdirSync(dir).filter((f) => /^skin-analysis\.w\d\d\.real\.json$/.test(f)).sort();
const weeks = files.map((f) => {
  const fx = JSON.parse(readFileSync(new URL(f, dir), "utf8"));
  const scores = {}; let overall, skinAge;
  for (const o of fx.response.data.results.output) {
    if (o.type === "all") overall = o.score;
    else if (o.type === "skin_age") skinAge = o.score;
    else if (typeof o.raw_score === "number") scores[o.type] = { raw: o.raw_score, ui: o.ui_score, mask: o.mask_urls[0] };
  }
  return { week: fx._meta.week, recorded: fx._meta.source.match(/\d{4}-\d\d-\d\d/)?.[0], overall, skinAge, scores };
});
writeFileSync(new URL("../lib/demo-series.ts", import.meta.url),
`// GENERATED by scripts/build-demo-series.mjs from fixtures/series/*.real.json. Do not edit by hand.
// Every number here is a REAL YouCam Skin Analysis v2.1 response (SD, 8 concerns) on week N of the synthetic face series.
import type { ConcernKey, ConcernScore } from "./types";
export interface SeriesWeek { week: number; recorded: string; overall: number; skinAge: number; scores: Record<ConcernKey, ConcernScore> }
export const DEMO_SERIES: SeriesWeek[] = ${JSON.stringify(weeks, null, 1)};
`);
console.log(`wrote ${weeks.length} weeks`);
